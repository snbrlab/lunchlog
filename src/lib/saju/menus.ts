// 일간 오행이 팔자에 몇 개인가로 세기 판정
export function strengthOf(dayElementCount: number): Strength {
  if (dayElementCount >= 4) return 'strong';
  if (dayElementCount >= 2) return 'mid';
  return 'weak';
}

