// 후보 중 하나를 인덱스로 선택. 운명 메뉴는 십성축 index(0~4)로, 궁합 메뉴는 seed 로 호출.
export function pickMenu(element: Element, strength: Strength, idx: number): string {
  const pool = MENU_POOL[element][strength];
  return pool[((idx % pool.length) + pool.length) % pool.length]!;
}
